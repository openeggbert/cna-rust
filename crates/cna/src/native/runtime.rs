/// Reads a CNA UTF-8 string through its canonical size/copy pair.
/// The copy half of CNA's size-then-copy pair, when the size is already known.
///
/// The CNB cursor's string read is destructive -- it consumes the string and
/// reports its size in one call -- so asking for the size a second time would
/// read the next string instead. This takes the count that read reported.
pub(crate) fn read_string_of_size(
    bytes: u64,
    check: impl Fn(sys::CNA_Result) -> Result<()>,
    copy: impl Fn(*mut core::ffi::c_char, u64, *mut u64) -> sys::CNA_Result,
) -> Result<String> {
    read_string(check, |out| {
        // SAFETY-free: this closure only reports the count already measured.
        unsafe { *out = bytes };
        sys::CNA_RESULT_SUCCESS
    }, copy)
}

pub(crate) fn read_string(
    check: impl Fn(sys::CNA_Result) -> Result<()>,
    size: impl Fn(*mut u64) -> sys::CNA_Result,
    copy: impl Fn(*mut core::ffi::c_char, u64, *mut u64) -> sys::CNA_Result,
) -> Result<String> {
    let mut bytes = 0_u64;
    check(size(&mut bytes))?;
    let capacity =
        usize::try_from(bytes).map_err(|_| CnaError::InvalidInput("CNA text is too large"))?;
    if capacity == 0 {
        return Ok(String::new());
    }
    let mut buffer = vec![0_u8; capacity];
    let mut written = 0_u64;
    check(copy(
        buffer.as_mut_ptr().cast::<core::ffi::c_char>(),
        bytes,
        &mut written,
    ))?;
    let written =
        usize::try_from(written).map_err(|_| CnaError::InvalidInput("CNA text is too large"))?;
    buffer.truncate(written.min(capacity));
    while buffer.last() == Some(&0) {
        buffer.pop();
    }
    String::from_utf8(buffer).map_err(|_| CnaError::InvalidInput("CNA text is not valid UTF-8"))
}
